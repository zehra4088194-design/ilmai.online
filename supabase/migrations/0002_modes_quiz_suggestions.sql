-- ---------- profile: who is the user? ----------
alter table public.profiles add column if not exists audience text not null default 'student' check (audience in ('student','teacher'));
alter table public.profiles add column if not exists grade text;
grant update (audience, grade) on public.profiles to authenticated;

alter table public.conversations add column if not exists mode text;

-- ---------- modes (the "plugins" list in the sidebar) ----------
create table if not exists public.modes (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  audience text not null default 'both' check (audience in ('student','teacher','both')),
  name text not null,
  name_ur text,
  icon text not null default 'sparkles',
  description text not null default '',
  system_prompt text not null default '',   -- hidden instructions added to every chat in this mode
  starters jsonb not null default '[]',     -- example prompts shown on the empty screen
  tool text,                                -- null | 'quiz'  (special UI shown on the empty screen)
  is_active boolean not null default true,
  sort_order int not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.modes enable row level security;
create policy "modes readable" on public.modes for select using (is_active and auth.uid() is not null);

-- ---------- quizzes ----------
create table if not exists public.quizzes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  conversation_id uuid references public.conversations(id) on delete set null,
  topic text not null,
  config jsonb not null default '{}',       -- {count, difficulty, kind, language}
  questions jsonb not null,                 -- [{type, question, options[], answer, explanation}]
  model text,
  created_at timestamptz not null default now()
);
create index if not exists quizzes_user_idx on public.quizzes (user_id, created_at desc);

create table if not exists public.quiz_attempts (
  id uuid primary key default gen_random_uuid(),
  quiz_id uuid not null references public.quizzes(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  answers jsonb not null,                   -- [selectedIndex | -1]
  score int not null,
  total int not null,
  duration_s int,
  created_at timestamptz not null default now()
);
create index if not exists attempts_quiz_idx on public.quiz_attempts (quiz_id, created_at desc);
create index if not exists attempts_created_idx on public.quiz_attempts (created_at desc);

alter table public.quizzes enable row level security;
alter table public.quiz_attempts enable row level security;
create policy "own quizzes"  on public.quizzes       for select using (auth.uid() = user_id);
create policy "own attempts" on public.quiz_attempts for select using (auth.uid() = user_id);

